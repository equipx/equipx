// Generates supabase/seed.sql from /content/*.json + content/missions.json.
// Idempotent: upserts keyed on natural keys (so uuids, and student progress that references them, survive
// a re-seed), children that are not in content are deleted, steps/safety rules/related parts are replaced.
// Run from repo root: `npm run db:seed-sql`, then apply with
//   set -a; . supabase/.env; set +a; psql "$DATABASE_URL" -v ON_ERROR_STOP=1 --single-transaction -f supabase/seed.sql
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const readJson = (...s) => JSON.parse(fs.readFileSync(path.join(repo, ...s), 'utf8'));

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs) => `array[${xs.map(q).join(', ')}]::text[]`;
const inList = (xs) => (xs.length ? xs.map(q).join(', ') : 'null');

const index = readJson('content', 'index.json');
const missions = readJson('content', 'missions.json').missions;
const out = [];
const w = (s = '') => out.push(s);

w('-- GENERATED by tools/supabase/seed.mjs from /content. Do not hand-edit; run `npm run db:seed-sql`.');
w('-- Idempotent: safe to re-run. Does not touch student activity or hotspot overrides.');
w('-- Apply in ONE transaction: psql -v ON_ERROR_STOP=1 --single-transaction -f supabase/seed.sql');
w();

const counts = { equipment: 0, parts: 0, safety: 0, procedures: 0, steps: 0, faults: 0, options: 0, related: 0, quizzes: 0, questions: 0, missions: 0, tasks: 0 };

for (const { id } of index.devices) {
  const d = readJson('content', `${id}.json`);
  const e = q(d.id);
  counts.equipment++;
  w(`-- ===== ${d.id} =====`);
  w(`insert into public.equipment (id, name, category, summary, overview, model_asset, default_camera_orbit, model_credit, layout, published)
values (${e}, ${q(d.name)}, ${q(d.category)}, ${q(d.summary)}, ${q(d.overview)}, ${q(d.model.asset)}, ${q(d.model.cameraOrbit)}, ${q(d.model.credit)}, ${q(JSON.stringify(d.layout))}::jsonb, true)
on conflict (id) do update set name = excluded.name, category = excluded.category, summary = excluded.summary,
  overview = excluded.overview, model_asset = excluded.model_asset, default_camera_orbit = excluded.default_camera_orbit,
  model_credit = excluded.model_credit, layout = excluded.layout, published = true;`);

  // parts (hotspot_position/normal overrides are left untouched)
  for (const p of d.parts) {
    counts.parts++;
    w(`insert into public.parts (equipment_id, id, number, name, function, usage, safety, node_name)
values (${e}, ${q(p.id)}, ${p.number}, ${q(p.name)}, ${q(p.function)}, ${q(p.usage)}, ${arr(p.safety ?? [])}, ${q(p.id)})
on conflict (equipment_id, id) do update set number = excluded.number, name = excluded.name, function = excluded.function,
  usage = excluded.usage, safety = excluded.safety, node_name = excluded.node_name;`);
  }
  w(`delete from public.parts where equipment_id = ${e} and id not in (${inList(d.parts.map((p) => p.id))});`);

  // safety rules: replace
  w(`delete from public.safety_rules where equipment_id = ${e};`);
  (d.safetyRules ?? []).forEach((t, i) => {
    counts.safety++;
    w(`insert into public.safety_rules (equipment_id, sort_order, text) values (${e}, ${i + 1}, ${q(t)});`);
  });

  // procedures + steps
  d.procedures.forEach((pr, i) => {
    counts.procedures++;
    w(`insert into public.procedures (equipment_id, slug, title, sort_order) values (${e}, ${q(pr.id)}, ${q(pr.title)}, ${i + 1})
on conflict (equipment_id, slug) do update set title = excluded.title, sort_order = excluded.sort_order;`);
    w(`delete from public.procedure_steps where procedure_id = (select id from public.procedures where equipment_id = ${e} and slug = ${q(pr.id)});`);
    pr.steps.forEach((s, j) => {
      counts.steps++;
      w(`insert into public.procedure_steps (procedure_id, equipment_id, step_number, text, part_id)
select id, ${e}, ${j + 1}, ${q(s.text)}, ${q(s.partId || null)} from public.procedures where equipment_id = ${e} and slug = ${q(pr.id)};`);
    });
  });
  w(`delete from public.procedures where equipment_id = ${e} and slug not in (${inList(d.procedures.map((p) => p.id))});`);

  // faults + options + related parts
  d.faults.forEach((f, i) => {
    counts.faults++;
    const sc = `(select id from public.fault_scenarios where equipment_id = ${e} and slug = ${q(f.id)})`;
    w(`insert into public.fault_scenarios (equipment_id, slug, symptom, explanation, sort_order) values (${e}, ${q(f.id)}, ${q(f.symptom)}, ${q(f.explanation)}, ${i + 1})
on conflict (equipment_id, slug) do update set symptom = excluded.symptom, explanation = excluded.explanation, sort_order = excluded.sort_order;`);
    w(`update public.fault_options set is_correct = false where scenario_id = ${sc};`);
    f.options.forEach((o, j) => {
      counts.options++;
      w(`insert into public.fault_options (scenario_id, slug, text, is_correct, sort_order)
select id, ${q(o.id)}, ${q(o.text)}, ${o.id === f.correctOptionId}, ${j + 1} from public.fault_scenarios where equipment_id = ${e} and slug = ${q(f.id)}
on conflict (scenario_id, slug) do update set text = excluded.text, is_correct = excluded.is_correct, sort_order = excluded.sort_order;`);
    });
    w(`delete from public.fault_options where scenario_id = ${sc} and slug not in (${inList(f.options.map((o) => o.id))});`);
    w(`delete from public.fault_related_parts where scenario_id = ${sc};`);
    for (const pid of f.relatedPartIds ?? []) {
      counts.related++;
      w(`insert into public.fault_related_parts (scenario_id, equipment_id, part_id)
select id, ${e}, ${q(pid)} from public.fault_scenarios where equipment_id = ${e} and slug = ${q(f.id)};`);
    }
  });
  w(`delete from public.fault_scenarios where equipment_id = ${e} and slug not in (${inList(d.faults.map((f) => f.id))});`);

  // quizzes + questions
  d.quizzes.forEach((z, i) => {
    counts.quizzes++;
    const qz = `(select id from public.quizzes where equipment_id = ${e} and slug = ${q(z.id)})`;
    w(`insert into public.quizzes (equipment_id, slug, title, time_limit_sec, sort_order) values (${e}, ${q(z.id)}, ${q(z.title)}, ${z.timeLimitSec ?? 'null'}, ${i + 1})
on conflict (equipment_id, slug) do update set title = excluded.title, time_limit_sec = excluded.time_limit_sec, sort_order = excluded.sort_order;`);
    z.questions.forEach((qq, j) => {
      counts.questions++;
      w(`insert into public.quiz_questions (quiz_id, slug, sort_order, prompt, options, correct_index, explanation)
select id, ${q(qq.id)}, ${j + 1}, ${q(qq.prompt)}, ${arr(qq.options)}, ${qq.correctIndex}, ${q(qq.explanation ?? '')} from public.quizzes where equipment_id = ${e} and slug = ${q(z.id)}
on conflict (quiz_id, slug) do update set sort_order = excluded.sort_order, prompt = excluded.prompt, options = excluded.options,
  correct_index = excluded.correct_index, explanation = excluded.explanation;`);
    });
    w(`delete from public.quiz_questions where quiz_id = ${qz} and slug not in (${inList(z.questions.map((x) => x.id))});`);
  });
  w(`delete from public.quizzes where equipment_id = ${e} and slug not in (${inList(d.quizzes.map((x) => x.id))});`);
  w();
}


// missions (after all devices so task references resolve)
w('-- ===== missions =====');
missions.forEach((m) => {
  counts.missions++;
  const mid = `(select id from public.missions where slug = ${q(m.id)})`;
  w(`insert into public.missions (slug, title, description, equipment_id, published) values (${q(m.id)}, ${q(m.title)}, ${q(m.description)}, ${q(m.deviceId ?? null)}, true)
on conflict (slug) do update set title = excluded.title, description = excluded.description, equipment_id = excluded.equipment_id, published = true;`);
  // tasks upsert on (mission_id, sort_order) so progress rows survive
  m.tasks.forEach((t, i) => {
    counts.tasks++;
    const proc = t.procedureId ? `(select id from public.procedures where equipment_id = ${q(t.deviceId)} and slug = ${q(t.procedureId)})` : 'null';
    const quiz = t.quizId ? `(select id from public.quizzes where equipment_id = ${q(t.deviceId)} and slug = ${q(t.quizId)})` : 'null';
    w(`insert into public.mission_tasks (mission_id, sort_order, task_type, title, equipment_id, part_id, procedure_id, quiz_id, min_score_pct)
values (${mid}, ${i + 1}, ${q(t.type)}, ${q(t.title)}, ${q(t.deviceId)}, ${q(t.partId ?? null)}, ${proc}, ${quiz}, ${t.minScorePct ?? 70})
on conflict (mission_id, sort_order) do update set task_type = excluded.task_type, title = excluded.title, equipment_id = excluded.equipment_id,
  part_id = excluded.part_id, procedure_id = excluded.procedure_id, quiz_id = excluded.quiz_id, min_score_pct = excluded.min_score_pct;`);
  });
  w(`delete from public.mission_tasks where mission_id = ${mid} and sort_order > ${m.tasks.length};`);
});

fs.writeFileSync(path.join(repo, 'supabase', 'seed.sql'), out.join('\n') + '\n');
console.log('wrote supabase/seed.sql', JSON.stringify(counts));
